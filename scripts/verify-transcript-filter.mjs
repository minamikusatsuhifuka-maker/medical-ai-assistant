// 検証: /api/transcribe のハルシネーション除去（app/lib/transcript-filter.js）の単体 assert
// 実行: node scripts/verify-transcript-filter.mjs
// 「①文全体一致」の定義: 文からパターンに当たる部分を取り除いた残りが、空白・句読点・敬語/終助詞の語尾（します/いたします/ございます/です/ね…）だけなら、その文を消す
import { filterTranscript, filterTranscriptCore, PHRASE_RULES, CONTAINS_RULES, FILLER_RULES, splitSentences } from "../app/lib/transcript-filter.js";

let pass = 0;
const eq = (got, want, msg) => {
  if (got !== want) { console.error(`❌ ${msg}\n   期待: ${JSON.stringify(want)}\n   実際: ${JSON.stringify(got)}`); process.exit(1); }
  pass++; console.log("  ✓ " + msg);
};
const f = (t) => filterTranscript(t).text;

console.log("── 指示書の必須ケース");
eq(f("よろしくお願いします。では診ていきますね。かゆみはどうですか"), "では診ていきますね。かゆみはどうですか", "「よろしくお願いします。」の1文だけ消え、残りの会話が残る");
eq(f("やっぱり冬になると乾燥しますね"), "やっぱり冬になると乾燥しますね", "「〜り」で終わる語を含む文が全文残る");
eq(f("お写真を撮影しますね。背中を見せてください"), "お写真を撮影しますね。背中を見せてください", "「撮影」を含む文が全文残る");
eq(f("ご視聴ありがとうございました"), "", "「ご視聴ありがとうございました」単独は空");
const fo = filterTranscript("診察の本文です", () => { throw new Error("注入した例外"); });
eq(fo.text, "診察の本文です", "フィルタ内で例外 → 無加工のテキストを返す(fail-open)");
eq(fo.failOpen, true, "fail-open の印が付く");

console.log("── 旧実装でチャンクごと消えていた文（すべて残る）");
for (const s of ["塗り始めてからかなり良くなりました。やっぱり", "次回の予約を登録しておきます", "カメラで拡大して見ますね", "保湿剤を編集…いや、保湿剤を追加しますね",
  "ステロイドを1日2回塗ってください。お願いします", "次回も同じお薬で様子を見ましょう", "びらんがあるのでビランと書いておきます", "ご覧いただけますか、ここが赤いところです",
  "リンゴを食べると口の周りが痒くなります", "漢方の薬草は使っていません", "痒みはあまり変わらなかったです…"]) eq(f(s), s, `残る: ${s}`);

console.log("── 旧「5文字以下は空」を撤廃（短い返事が残る）");
for (const s of ["かゆいです", "痛いです", "効きました", "出ません", "治りました"]) eq(f(s), s, `残る: ${s}`);

console.log("── ① 文全体一致 44件: 挨拶だけの1文は消え、会話の一部なら残る");
const PHRASE_SAMPLES = {
  P1: "ご視聴ありがとうございました", P2: "ご覧いただきありがとうございました", P3: "高評価お願いします", P4: "良い1日を", P5: "本日はご覧いただきありがとうございました",
  P6: "お疲れ様でした", P7: "それではまた", P8: "バイバイ", P9: "See you", P10: "ご覧くださりありがとう", P11: "ありがとうございました", P12: "本当にありがとう",
  P13: "また会いましょう", P14: "お楽しみに", P15: "よろしくお願いします", P16: "お元気で", P17: "さようなら", P18: "おやすみなさい", P19: "こんにちは",
  P20: "どうもありがとう", P21: "見てくれてありがとう", P22: "ありがとうございます", P23: "ありがとうございました", P24: "どうもありがとうございます",
  P25: "聴いてくれてありがとう", P26: "聞いてくれてありがとう", P27: "応援ありがとう", P28: "いつもありがとう", P29: "以上です", P30: "終わります",
  P31: "それでは失礼します", P32: "失礼します", P33: "よろしくお願いいたします", P34: "どうぞよろしく", P35: "次回もよろしくお願いします",
  P36: "またお会いしましょう", P37: "またね", P38: "じゃあね", P39: "ではでは", P40: "お楽しみに", P41: "行ってらっしゃい", P42: "お気をつけて",
  P43: "お大事にしてください", P44: "お元気でね",
};
eq(Object.keys(PHRASE_SAMPLES).length, PHRASE_RULES.length, "① のサンプルが44件すべてにある");
for (const [id, re] of PHRASE_RULES) {
  const s = PHRASE_SAMPLES[id];
  eq(re.test(s), true, `${id} ${re} はサンプル「${s}」に当たる`);
  eq(f(s + "。"), "", `${id} 「${s}。」単独 → 消える`);
  eq(f(s + "。 二週間前から首が痒いです。"), "二週間前から首が痒いです。", `${id} 「${s}。」の後ろの会話は残る`);
  const mixed = `${s}、それで塗り薬はどうしましたか`;
  if (CONTAINS_RULES.some(([, c]) => c.test(s))) eq(f(mixed), "", `${id} ②の部分一致にも当たる語のため「${mixed}」は文ごと消える（②優先）`);
  else eq(f(mixed), mixed, `${id} 同じ文に会話が続く「${mixed}」→ 文ごと残る`);
}

console.log("── ② 部分一致（その語を含む文だけ消す）");
eq(CONTAINS_RULES.length, 37, "② は37件");
eq(f("チャンネル登録よろしくお願いします。 かゆみはどうですか。"), "かゆみはどうですか。", "チャンネル登録の文だけ消える");
eq(f("Thank you for watching! 背中の湿疹です"), "背中の湿疹です", "英語の定型文だけ消える（英文は単語で分割しない）");
eq(f("字幕は自動生成です。 ステロイドを塗ります。"), "ステロイドを塗ります。", "字幕の文だけ消える");

console.log("── ③ 相づち・記号だけ（チャンク全体のときだけ空）");
eq(FILLER_RULES.length, 27, "③ は27件");
eq(f("はい。"), "", "「はい。」だけのチャンクは空");
eq(f("はい。 痒みはあります。"), "はい。 痒みはあります。", "会話の中の「はい。」は消さない（患者の返事を残す）");
eq(f("[音楽]"), "", "[音楽] だけは空");
eq(f("よろしくお願いします。 はい。"), "", "挨拶を除いた残りが相づちだけなら空");
eq(f("silence"), "", "silence 単独は空");
eq(f("since last week it itches"), "since last week it itches", "旧 /^[silence]/i の誤爆（s/i/l/e/n/c 始まり）が直っている");

console.log("── 繰り返しループ（従来どおり空）");
eq(f("はい はい はい はい はい はい"), "", "同じ語の繰り返しは空");

console.log("── 分割と記録");
eq(splitSentences("あ。 い。  う").map((x) => x.s + x.sep).join(""), "あ。 い。  う", "文分割は元のテキストに戻せる");
const r = filterTranscriptCore("お疲れ様でした。 かゆいです");
eq(JSON.stringify(r.dropped), JSON.stringify([{ rule: "P6", len: 8 }]), "除去の記録はパターン番号と文字数だけ（本文なし）");

console.log(`\n✅ 全 ${pass} 件 PASS`);
